# System profile settings for Grain Media GM8210

# Set default PATH
export PATH="/usr/sbin:/usr/bin:/sbin:/bin"

# Set default shell prompt
export PS1='\u@\h:\w\$ '

# Set default editor
export EDITOR='/bin/vi'

# Set PAGER for less
export PAGER='/usr/bin/less'

# Locale settings
export LC_ALL='C'
